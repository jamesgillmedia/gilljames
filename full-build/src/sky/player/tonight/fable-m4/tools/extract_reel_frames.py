#!/usr/bin/env python3
"""Extract evenly spaced still frames from every Demo Reel clip, as small webp thumbs.

Reads the clip list from js/reelshots.js (GJ_REEL), takes each clip's mp4 under
media/pro2/reel/<f>.mp4, and writes
    media/pro2/reel/frames/<f>-<kk>.webp      (fits inside 96x56, quality 60)
plus the manifest the reel card reads
    js/reelframes.js                          window.GJ_REELFR = {"a/000":[n,w,h,seconds], ...}

Frame k of n sits at the middle of its slice: t = (k + 0.5) * seconds / n, so the
frames are evenly spaced and never fall on the very first or last frame.
n = clamp(ceil(seconds * FPS), MIN, MAX).

Needs ffmpeg and ffprobe on PATH (ffmpeg built with libwebp).
Usage, from tonight/fable-m4:
    python3 tools/extract_reel_frames.py            # everything
    python3 tools/extract_reel_frames.py a/000 b/010  # only these clips
"""
import json, math, os, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
REEL = os.path.join(ROOT, 'media', 'pro2', 'reel')
OUT = os.path.join(REEL, 'frames')
FPS, MIN, MAX = 8, 6, 12
BOX_W, BOX_H = 96, 56
QUALITY = '60'


def clips():
    src = open(os.path.join(ROOT, 'js', 'reelshots.js'), encoding='utf-8').read()
    return [c['f'] for c in json.loads(src[src.index('['):src.rindex(']') + 1])]


def probe(path, entries):
    out = subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', entries, '-of', 'csv=p=0', path], text=True)
    return out.strip().split(',')


def frame_count(seconds):
    return max(MIN, min(MAX, math.ceil(seconds * FPS)))


def extract(f):
    mp4 = os.path.join(REEL, f + '.mp4')
    seconds = float(probe(mp4, 'format=duration')[0])
    n = frame_count(seconds)
    scale = "scale='if(gt(iw/ih,%d/%d),%d,-2)':'if(gt(iw/ih,%d/%d),-2,%d)':flags=lanczos" % (BOX_W, BOX_H, BOX_W, BOX_W, BOX_H, BOX_H)
    for k in range(n):
        out = os.path.join(OUT, '%s-%02d.webp' % (f, k))
        os.makedirs(os.path.dirname(out), exist_ok=True)
        t = (k + 0.5) * seconds / n
        subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-ss', '%.4f' % t, '-i', mp4, '-frames:v', '1',
                               '-vf', scale, '-c:v', 'libwebp', '-quality', QUALITY, out])
    w, h = [int(v) for v in probe(os.path.join(OUT, '%s-00.webp' % f), 'stream=width,height')]
    return f, [n, w, h, round(seconds, 3)]


def main():
    want = sys.argv[1:] or clips()
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as ex:
        done = dict(ex.map(extract, want))
    manifest = os.path.join(ROOT, 'js', 'reelframes.js')
    merged = {}
    if sys.argv[1:] and os.path.exists(manifest):
        old = open(manifest, encoding='utf-8').read()
        merged = json.loads(old[old.index('{'):old.rindex('}') + 1])
    merged.update(done)
    order = {f: i for i, f in enumerate(clips())}
    body = json.dumps({k: merged[k] for k in sorted(merged, key=lambda k: order.get(k, 1e9))}, separators=(',', ':'))
    with open(manifest, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/extract_reel_frames.py. clip -> [frames, thumb w, thumb h, seconds]; thumbs: media/pro2/reel/frames/<clip>-<kk>.webp */\n')
        fh.write('window.GJ_REELFR=' + body + ';\n')
    print('%d clips, %d frames' % (len(done), sum(v[0] for v in done.values())))


if __name__ == '__main__':
    main()
