#!/usr/bin/env python3
"""Extract evenly spaced still frames from every film loop, as small webp thumbs, for the frame rail.

For each film in data.json that has a loop under ../media/film/<slug>/ (loop-720.mp4 for the films that use the 720 rung,
else loop-480.mp4 -- the same file playback.js picks), writes
    media/loopframes/<slug>-<kk>.webp        (fits inside 96x56, quality 60)
plus the manifest the player reads
    js/loopframes.js                         window.GJ_LOOPFR = {"<slug>": [frames, thumb w, thumb h, seconds], ...}

Frame k of n sits at the middle of its slice, t = (k + 0.5) * seconds / n, so the frames are evenly spaced.
n = clamp(round(seconds * 2.5), 12, 20).

Needs ffmpeg and ffprobe on PATH (ffmpeg built with libwebp).
Usage, from tonight/fable-m4:
    python3 tools/extract_loop_frames.py
"""
import json, math, os, subprocess
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
FILMS = os.path.abspath(os.path.join(ROOT, '..', 'media', 'film'))
OUT = os.path.join(ROOT, 'media', 'loopframes')
HERO720 = {'weird-kid', 'one-with-the-devil', 'mark-snowwater'}
BOX_W, BOX_H = 96, 56


def slugs():
    data = json.load(open(os.path.join(ROOT, 'data.json'), encoding='utf-8'))
    out = []
    def walk(o):
        if isinstance(o, dict):
            if o.get('kind') == 'film' and o.get('slug') and not o.get('nov9'):
                out.append(o['slug'])
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(data)
    return [s for s in dict.fromkeys(out) if loop_file(s)]


def loop_file(slug):
    for rung in (['720', '480'] if slug in HERO720 else ['480']):
        f = os.path.join(FILMS, slug, 'loop-%s.mp4' % rung)
        if os.path.exists(f):
            return f
    return None


def probe(path, entries):
    return subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', entries, '-of', 'csv=p=0', path], text=True).strip().split(',')


def extract(slug):
    mp4 = loop_file(slug)
    seconds = float(probe(mp4, 'format=duration')[0])
    n = max(12, min(20, round(seconds * 2.5)))
    scale = "scale='if(gt(iw/ih,%d/%d),%d,-2)':'if(gt(iw/ih,%d/%d),-2,%d)':flags=lanczos" % (BOX_W, BOX_H, BOX_W, BOX_W, BOX_H, BOX_H)
    os.makedirs(OUT, exist_ok=True)
    for k in range(n):
        t = (k + 0.5) * seconds / n
        subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-ss', '%.4f' % t, '-i', mp4, '-frames:v', '1', '-vf', scale,
                               '-c:v', 'libwebp', '-quality', '60', os.path.join(OUT, '%s-%02d.webp' % (slug, k))])
    w, h = [int(v) for v in probe(os.path.join(OUT, '%s-00.webp' % slug), 'stream=width,height')]
    return slug, [n, w, h, round(seconds, 3)]


def main():
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as ex:
        done = dict(ex.map(extract, slugs()))
    with open(os.path.join(ROOT, 'js', 'loopframes.js'), 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/extract_loop_frames.py. slug -> [frames, thumb w, thumb h, seconds]; thumbs: media/loopframes/<slug>-<kk>.webp */\n')
        fh.write('window.GJ_LOOPFR=' + json.dumps(done, separators=(',', ':')) + ';\n')
    print('%d films, %d frames' % (len(done), sum(v[0] for v in done.values())))


if __name__ == '__main__':
    main()
